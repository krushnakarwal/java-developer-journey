package com.java_basics;

public class Relational_operator {
	public static void main(String[] args) {
		int num1 = 25;
		int num2 = 40;
		
		System.out.println(num1 == num2);
		System.out.println(num1 != num2);
		System.out.println(num1 > num2);
		System.out.println(num1 < num2);
		System.out.println(num1 >= num2);
		System.out.println(num1 <= num2);
		

	}

}
