package com.java_basics;

public class DataTypes {
	public static void main(String[] args) {
	
	byte    a = 110;
	short   b = 32767;
	int     c = 2131;
	long    e = 23423;
	float   f = 99.99f;
	double  g = 88.8999999;
	char    h = 'k';
	boolean i = true;
	
	System.out.println("Byte Data Type = "+a);
	System.out.println("short Data Type = "+b);
	System.out.println("int data Type = "+c);
	System.out.println("long data Type = "+e);
	System.out.println("float data Type = "+f);
	System.out.println("double data Type = "+g);
	System.out.println("char data Type = "+h);
	System.out.println("boolean data Type = "+i);	
}
	}



