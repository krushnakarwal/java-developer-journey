package com.java_basics;

public class AssignmentOperator {
	public static void main(String [] args) {
		int number = 10;
		int result;
		
		System.out.println(number);
		 
		result = number=5;
		System.out.println(result);
		
		result = number+=10;
		System.out.println(result);
		
		result = number-=10;
		System.out.println(result);
		
		result = number*=5;
		System.out.println(result);
		
		result = number/=5;
		System.out.println(result);
		
		result = number%=3;
		System.out.println(result);
	}

}
