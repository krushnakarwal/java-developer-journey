package com.java_basics;

public class Ternary_operator {
	    public static void main(String[] args) {

	        int age = 20;

	        // Ternary Operator
	        String result = (age >= 18) ? "Eligible" : "Not Eligible";

	        System.out.println("Age = " + age);
	        System.out.println("Result = " + result);
	    }
	}

	